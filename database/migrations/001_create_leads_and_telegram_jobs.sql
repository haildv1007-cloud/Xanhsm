CREATE TABLE IF NOT EXISTS leads (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    public_id VARCHAR(24) NOT NULL,
    submission_token VARCHAR(64) NOT NULL,
    full_name VARCHAR(100) NOT NULL,
    phone VARCHAR(20) NOT NULL,
    zalo VARCHAR(20) NULL,
    citizen_id_encrypted TEXT NULL,
    region VARCHAR(64) NOT NULL,
    vehicle VARCHAR(64) NOT NULL,
    cooperation_type VARCHAR(64) NOT NULL,
    source_page VARCHAR(32) NOT NULL,
    form_location VARCHAR(16) NOT NULL,
    source_url VARCHAR(2048) NULL,
    utm_source VARCHAR(255) NULL,
    utm_medium VARCHAR(255) NULL,
    utm_campaign VARCHAR(255) NULL,
    utm_content VARCHAR(255) NULL,
    utm_term VARCHAR(255) NULL,
    click_id VARCHAR(255) NULL,
    ip_hash CHAR(64) NOT NULL,
    status ENUM('new', 'contacted', 'pending_documents', 'completed') NOT NULL DEFAULT 'new',
    created_at DATETIME NOT NULL,
    updated_at DATETIME NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_leads_public_id (public_id),
    UNIQUE KEY uq_leads_submission_token (submission_token),
    KEY idx_leads_phone (phone),
    KEY idx_leads_ip_created (ip_hash, created_at),
    KEY idx_leads_status_created (status, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS telegram_jobs (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    lead_id BIGINT UNSIGNED NOT NULL,
    job_type VARCHAR(32) NOT NULL DEFAULT 'new_lead',
    status ENUM('pending', 'processing', 'retry', 'sent', 'failed') NOT NULL DEFAULT 'pending',
    attempts SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    next_attempt_at DATETIME NOT NULL,
    locked_at DATETIME NULL,
    sent_at DATETIME NULL,
    telegram_message_id VARCHAR(64) NULL,
    last_error VARCHAR(255) NULL,
    created_at DATETIME NOT NULL,
    updated_at DATETIME NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_telegram_lead_type (lead_id, job_type),
    KEY idx_telegram_queue (status, next_attempt_at),
    CONSTRAINT fk_telegram_jobs_lead FOREIGN KEY (lead_id) REFERENCES leads (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
